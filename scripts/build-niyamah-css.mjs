import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
const root = process.cwd();
const input = path.join(root, 'components/niyamah/niyamah.source.css');
const result = await postcss([tailwind({base: root, optimize: false})]).process(await fs.readFile(input, 'utf8'), {from: input});
// Scope both Tailwind's reset and utilities to the two imported sections.
// Flatten layers so the host project's unlayered stylesheet cannot override them.
result.root.walkAtRules('layer', rule => { if (rule.nodes) rule.replaceWith(...rule.nodes); else rule.remove(); });
result.root.walkRules(rule => {
 let p=rule.parent;
 while(p) { if(p.type==='rule' || (p.type==='atrule' && /keyframes/.test(p.name))) return; p=p.parent; }
 rule.selectors=rule.selectors.map(sel => {
   if (sel === ':root' || sel === ':host' || sel === 'html') return '.niyamah-copy';
   if (sel.startsWith('.niyamah-copy')) return sel;
   return `.niyamah-copy ${sel}`;
 });
});
await fs.writeFile(path.join(root, 'components/niyamah/niyamah.css'), '/* Generated by npm run build:niyamah-css. Edit niyamah.source.css. */\n'+result.root.toString());
console.log('Built scoped Niyamah stylesheet.');
